#!/usr/bin/env bash
# Shared, multi-app Caddy helpers for the GOWA OTP deployment.
#
# The VPS runs ONE Caddy instance for several apps:
#
#   /etc/caddy/Caddyfile              # base: global options + snippets + import
#   /etc/caddy/sites-enabled/*.caddy  # one file per app, owned by that app's repo
#
# This repository only ever writes its own site file, validates the whole
# configuration, and then gracefully reloads Caddy. If validation fails the
# previous file is restored, so a broken GOWA deploy cannot take PayConnect (or
# any other app) offline.
#
# All paths can be overridden through the environment, which makes the same
# scripts usable on any host (or inside a Caddy container with bind mounts):
#
#   GOWA_CADDY_BASE_FILE     default /etc/caddy/Caddyfile
#   GOWA_CADDY_SITES_DIR     default /etc/caddy/sites-enabled
#   GOWA_CADDY_BACKUP_DIR    default <sites-dir>/.backups
#   GOWA_CADDY_TAKEOVER      true = replace a foreign base Caddyfile (backup kept)
#   GOWA_CADDY_VALIDATE_CMD  custom validate command (containerised Caddy)
#   GOWA_CADDY_RELOAD_CMD    custom reload command (containerised Caddy)
set -euo pipefail

CADDY_BASE_FILE="${GOWA_CADDY_BASE_FILE:-/etc/caddy/Caddyfile}"
CADDY_SITES_DIR="${GOWA_CADDY_SITES_DIR:-/etc/caddy/sites-enabled}"
CADDY_BACKUP_DIR="${GOWA_CADDY_BACKUP_DIR:-${CADDY_SITES_DIR}/.backups}"
CADDY_LOCK_FILE="${GOWA_CADDY_LOCK_FILE:-${CADDY_SITES_DIR}/.deploy.lock}"
CADDY_MARKER="# Managed by gowa deploy scripts (vps-scripts/caddy)."
CADDY_MAX_BACKUPS="${GOWA_CADDY_MAX_BACKUPS:-10}"

caddy_import_line() {
  printf 'import %s/*.caddy' "$CADDY_SITES_DIR"
}

caddy_validate_site_id() {
  local site_id="$1"
  [[ "$site_id" =~ ^[a-z0-9][a-z0-9._-]*$ ]] ||
    die "invalid Caddy site id '${site_id}' (use lowercase letters, digits, '.', '_' or '-')"
  [[ "$site_id" != *".."* ]] || die "invalid Caddy site id '${site_id}'"
}

caddy_site_file() {
  printf '%s/%s.caddy' "$CADDY_SITES_DIR" "$1"
}

# Serialize deploys so two pipelines cannot reload Caddy from stale state.
caddy_lock() {
  mkdir -p "$CADDY_SITES_DIR"
  [[ -w "$CADDY_SITES_DIR" ]] ||
    die "${CADDY_SITES_DIR} is not writable; run as root or grant the deploy user ownership"
  if command -v flock >/dev/null 2>&1; then
    # The lock may be created by root during setup and opened by a non-root CI
    # user later, so keep it world-writable (it is only a flock target).
    (umask 000 && : >>"$CADDY_LOCK_FILE") 2>/dev/null || true
    chmod 0666 "$CADDY_LOCK_FILE" 2>/dev/null || true
    if ! exec 9>"$CADDY_LOCK_FILE" 2>/dev/null; then
      warn "cannot open ${CADDY_LOCK_FILE}; continuing without a deploy lock"
      return 0
    fi
    flock -w 60 9 || die "timed out waiting for the Caddy deploy lock (${CADDY_LOCK_FILE})"
  else
    warn "flock is unavailable; Caddy deploys are not serialized on this host"
  fi
}

caddy_unlock() {
  if command -v flock >/dev/null 2>&1; then
    flock -u 9 >/dev/null 2>&1 || true
  fi
}

# Run a command as root: direct when already root, sudo -n for CI users.
caddy_privileged() {
  if [[ "$(id -u)" -eq 0 ]]; then
    "$@"
  elif sudo -n true >/dev/null 2>&1; then
    sudo -n "$@"
  else
    "$@"
  fi
}

# Copy the current file aside; keep a bounded history per site.
caddy_backup_file() {
  local target="$1"
  local site_id="$2"
  local backup=""
  mkdir -p "$CADDY_BACKUP_DIR"
  if [[ -f "$target" ]]; then
    backup="${CADDY_BACKUP_DIR}/${site_id}.$(date -u +%Y%m%dT%H%M%SZ).$$"
    cp -p "$target" "$backup"
    caddy_prune_backups "$site_id"
  fi
  printf '%s' "$backup"
}

caddy_prune_backups() {
  local site_id="$1"
  local -a old=()
  mapfile -t old < <(ls -1t "${CADDY_BACKUP_DIR}/${site_id}."* 2>/dev/null || true)
  local i
  for ((i = CADDY_MAX_BACKUPS; i < ${#old[@]}; i++)); do
    rm -f "${old[$i]}"
  done
}

# True when the existing base file is one this repo generated before, a base
# generated by the PayConnect deploy scripts, or the stock Debian Caddyfile.
# Anything else is foreign and is left alone unless GOWA_CADDY_TAKEOVER=true.
caddy_base_is_replaceable() {
  local file="$1"
  [[ -f "$file" ]] || return 0
  grep -Fq "$CADDY_MARKER" "$file" && return 0
  # Base generated by the PayConnect deploy scripts on the same VPS.
  grep -Fq '# Managed by payconnect deploy scripts (vps-scripts/caddy).' "$file" && return 0
  # Stock Caddyfile installed by the caddy apt package.
  grep -Fq 'The Caddyfile is an easy way to configure your Caddy web server' "$file" && return 0
  return 1
}

caddy_write_base() {
  local output="$1"
  local acme_email="${2:-}"

  {
    printf '%s\n' "$CADDY_MARKER"
    printf '# Global settings only. Each app owns one file in %s/.\n' "$CADDY_SITES_DIR"
    printf '# Edit app routes in that directory, never here.\n\n'

    if [[ -n "$acme_email" ]]; then
      printf '{\n'
      printf '\temail %s\n' "$acme_email"
      printf '\t# Uncomment to use the Let'"'"'s Encrypt staging CA while testing:\n'
      printf '\t# acme_ca https://acme-staging-v02.api.letsencrypt.org/directory\n'
      printf '}\n\n'
    fi

    cat <<'SNIPPET'
# Shared security headers. Apps opt in with: import security_headers
(security_headers) {
	header {
		Strict-Transport-Security "max-age=31536000; includeSubDomains; preload"
		X-Content-Type-Options "nosniff"
		X-Frame-Options "SAMEORIGIN"
		Referrer-Policy "strict-origin-when-cross-origin"
		-Server
	}
}

SNIPPET

    printf '# One file per app, published by that app'"'"'s deploy pipeline.\n'
    printf '%s\n' "$(caddy_import_line)"
  } >"$output"
}

ensure_caddy_base() {
  local acme_email="${1:-}"
  local tmp=""

  # Keep an existing email when a later deploy does not pass one.
  if [[ -z "$acme_email" && -f "$CADDY_BASE_FILE" ]] && grep -Fq "$CADDY_MARKER" "$CADDY_BASE_FILE"; then
    acme_email="$(sed -n 's/^[[:space:]]*email[[:space:]]\{1,\}\([^[:space:]]*\).*/\1/p' "$CADDY_BASE_FILE" | head -n1)"
  fi

  local created_sites=false created_backups=false
  [[ -d "$CADDY_SITES_DIR" ]] || created_sites=true
  [[ -d "$CADDY_BACKUP_DIR" ]] || created_backups=true
  mkdir -p "$CADDY_SITES_DIR" "$CADDY_BACKUP_DIR"
  # Only set modes on creation: install-base.sh --owner may have widened the
  # directory to 0775 for a non-root deploy user, and root deploys must keep it.
  [[ "$created_sites" == true ]] && chmod 0755 "$CADDY_SITES_DIR" 2>/dev/null || true
  [[ "$created_backups" == true ]] && chmod 0755 "$CADDY_BACKUP_DIR" 2>/dev/null || true

  tmp="$(mktemp "${CADDY_BASE_FILE}.XXXXXX")"
  caddy_write_base "$tmp" "$acme_email"

  if [[ ! -f "$CADDY_BASE_FILE" ]]; then
    install -m 0644 "$tmp" "$CADDY_BASE_FILE"
    rm -f "$tmp"
    log "Created base Caddyfile ${CADDY_BASE_FILE} (imports ${CADDY_SITES_DIR}/*.caddy)"
    return 0
  fi

  if grep -Fq "$(caddy_import_line)" "$CADDY_BASE_FILE"; then
    if grep -Fq "$CADDY_MARKER" "$CADDY_BASE_FILE"; then
      if cmp -s "$tmp" "$CADDY_BASE_FILE"; then
        rm -f "$tmp"
        log "Base Caddyfile already up to date: ${CADDY_BASE_FILE}"
        return 0
      fi
      local backup
      backup="$(caddy_backup_file "$CADDY_BASE_FILE" "Caddyfile")"
      install -m 0644 "$tmp" "$CADDY_BASE_FILE"
      rm -f "$tmp"
      log "Updated base Caddyfile ${CADDY_BASE_FILE} (backup: ${backup})"
    else
      rm -f "$tmp"
      log "Base Caddyfile ${CADDY_BASE_FILE} already imports ${CADDY_SITES_DIR}; leaving it untouched"
    fi
    return 0
  fi

  if caddy_base_is_replaceable "$CADDY_BASE_FILE" || [[ "${GOWA_CADDY_TAKEOVER:-false}" == "true" ]]; then
    local backup
    backup="$(caddy_backup_file "$CADDY_BASE_FILE" "Caddyfile")"
    install -m 0644 "$tmp" "$CADDY_BASE_FILE"
    rm -f "$tmp"
    warn "Replaced ${CADDY_BASE_FILE} with the shared base config (backup: ${backup:-none})"
    return 0
  fi

  rm -f "$tmp"
  die "${CADDY_BASE_FILE} exists but does not import ${CADDY_SITES_DIR}/*.caddy.
Add this line to its global section and re-run:

    $(caddy_import_line)

Or set GOWA_CADDY_TAKEOVER=true to replace it (a timestamped backup is kept)."
}

# "https://api.example.com" -> "api.example.com", "http://1.2.3.4" -> "http://1.2.3.4"
caddy_site_addresses() {
  local public_base="$1"
  local extra_hosts="${2:-}"
  local scheme="${public_base%%://*}"
  local hostport="${public_base#*://}"
  hostport="${hostport%%/*}"
  hostport="${hostport%/}"

  local addresses
  if [[ "$scheme" == "https" ]]; then
    addresses="$hostport"
  else
    addresses="http://${hostport}"
  fi

  local item
  # shellcheck disable=SC2086 # deliberate word splitting on commas/spaces
  for item in ${extra_hosts//,/ }; do
    [[ -n "$item" ]] || continue
    item="${item%/}"
    if [[ "$item" == *"://"* ]]; then
      addresses="${addresses}, ${item}"
    elif [[ "$scheme" == "https" ]]; then
      addresses="${addresses}, ${item}"
    else
      addresses="${addresses}, http://${item}"
    fi
  done

  printf '%s' "$addresses"
}

caddy_site_template() {
  local template_dir
  template_dir="$(cd "$(dirname "${BASH_SOURCE[0]}")/../caddy" && pwd)"
  printf '%s/site.caddy.template' "$template_dir"
}

render_caddy_site() {
  local output="$1"
  local site_id="$2"
  local public_base="$3"
  local upstream="$4"
  local extra_hosts="${5:-}"

  local template_file
  template_file="$(caddy_site_template)"
  [[ -f "$template_file" ]] || die "Caddy site template not found: ${template_file}"

  local addresses
  addresses="$(caddy_site_addresses "$public_base" "$extra_hosts")"

  local headers='	import security_headers'
  # The shared snippet only exists when a shared base generates it. If an
  # operator maintains a base that merely imports sites-enabled, stay
  # self-contained and inline the headers.
  if ! grep -Eq '^[[:space:]]*\(security_headers\)' "$CADDY_BASE_FILE" 2>/dev/null; then
    headers=$(cat <<'HEADERS'
	header {
		Strict-Transport-Security "max-age=31536000; includeSubDomains; preload"
		X-Content-Type-Options "nosniff"
		X-Frame-Options "DENY"
		Referrer-Policy "no-referrer"
		-Server
	}
HEADERS
)
  fi

  local template
  template="$(cat "$template_file")"
  template="${template//@@SITE_ID@@/$site_id}"
  template="${template//@@SITE_ADDRESSES@@/$addresses}"
  template="${template//@@UPSTREAM@@/$upstream}"
  template="${template//@@HEADERS@@/$headers}"

  mkdir -p "$(dirname "$output")"
  printf '%s\n' "$template" >"$output"
  chmod 0644 "$output"
}

caddy_validate() {
  if [[ -n "${GOWA_CADDY_VALIDATE_CMD:-}" ]]; then
    bash -c "$GOWA_CADDY_VALIDATE_CMD"
    return
  fi
  command -v caddy >/dev/null 2>&1 || return 0
  caddy validate --config "$CADDY_BASE_FILE" --adapter caddyfile
}

caddy_reload() {
  # Containerised Caddy (or any non-systemd supervisor) can plug in its own
  # command, e.g.:
  #   GOWA_CADDY_RELOAD_CMD="docker exec caddy caddy reload --config /etc/caddy/Caddyfile --force"
  if [[ -n "${GOWA_CADDY_RELOAD_CMD:-}" ]]; then
    bash -c "$GOWA_CADDY_RELOAD_CMD"
    return
  fi
  if ! command -v systemctl >/dev/null 2>&1; then
    warn "systemctl not found; reload Caddy manually to apply ${CADDY_SITES_DIR}"
    return 0
  fi
  if systemctl is-active --quiet caddy; then
    if ! caddy_privileged systemctl reload caddy; then
      warn "systemctl reload caddy failed; trying a restart"
      caddy_privileged systemctl restart caddy
    fi
  else
    log "Starting the caddy service"
    caddy_privileged systemctl enable --now caddy
  fi
}

# Publish one app snippet atomically, validate, reload, and roll back on error.
publish_caddy_site() {
  local snippet="$1"
  local site_id="$2"
  local target staging backup=""

  caddy_validate_site_id "$site_id"
  [[ -f "$snippet" ]] || die "rendered Caddy snippet not found: ${snippet}"

  mkdir -p "$CADDY_SITES_DIR" "$CADDY_BACKUP_DIR"
  target="$(caddy_site_file "$site_id")"
  staging="$(mktemp "${CADDY_SITES_DIR}/.${site_id}.XXXXXX")"
  install -m 0644 "$snippet" "$staging"

  if [[ -f "$target" ]]; then
    backup="$(caddy_backup_file "$target" "$site_id")"
  fi
  mv -f "$staging" "$target"

  if ! command -v caddy >/dev/null 2>&1 && [[ -z "${GOWA_CADDY_VALIDATE_CMD:-}" ]]; then
    warn "caddy binary not found; wrote ${target} but skipped validation/reload"
    return 0
  fi

  local validation_output=""
  if ! validation_output="$(caddy_validate 2>&1)"; then
    caddy_restore_site "$target" "$backup"
    printf '%s\n' "$validation_output" >&2
    die "caddy validate failed; restored the previous version of ${target}"
  fi

  if ! caddy_reload; then
    caddy_restore_site "$target" "$backup"
    caddy_reload >/dev/null 2>&1 || true
    die "Caddy reload failed; restored the previous version of ${target}"
  fi

  log "Published ${target} and reloaded Caddy"
}

caddy_restore_site() {
  local target="$1"
  local backup="${2:-}"
  if [[ -n "$backup" && -f "$backup" ]]; then
    mv -f "$backup" "$target"
  else
    rm -f "$target"
  fi
}

# Remove this app's routes (used by teardown). Other apps are untouched.
remove_caddy_site() {
  local site_id="$1"
  caddy_validate_site_id "$site_id"
  local target backup=""
  target="$(caddy_site_file "$site_id")"
  [[ -f "$target" ]] || {
    log "No Caddy site file to remove: ${target}"
    return 0
  }

  backup="$(caddy_backup_file "$target" "$site_id")"
  rm -f "$target"

  if command -v caddy >/dev/null 2>&1; then
    if ! caddy_validate >/dev/null 2>&1; then
      caddy_restore_site "$target" "$backup"
      die "removing ${target} would break the Caddy config; restored it"
    fi
    caddy_reload || true
  fi
  log "Removed ${target}"
}

# Probe a site through the local Caddy, bypassing DNS.
caddy_probe() {
  local public_base="$1"
  local path="${2:-/health}"
  local scheme="${public_base%%://*}"
  local hostport="${public_base#*://}"
  hostport="${hostport%%/*}"
  hostport="${hostport%/}"
  local host="$hostport"
  local port="80"
  local url=""

  if [[ "$scheme" == "https" ]]; then
    port="443"
    url="https://${hostport}${path}"
  else
    url="http://${hostport}${path}"
  fi

  if [[ "$hostport" == *:* ]]; then
    host="${hostport%:*}"
    port="${hostport##*:}"
  fi

  curl -fsS --max-time 5 --resolve "${host}:${port}:127.0.0.1" "$url"
}

# HTTP status for the public host, still routed through loopback. Used to prove
# the site fragment is loaded before a certificate can be issued (DNS pending).
caddy_probe_http_status() {
  local public_base="$1"
  local path="${2:-/health}"
  local hostport="${public_base#*://}"
  hostport="${hostport%%/*}"
  hostport="${hostport%/}"
  local host="$hostport"
  local port="80"

  if [[ "$hostport" == *:* ]]; then
    host="${hostport%:*}"
    port="${hostport##*:}"
  fi

  curl -sS -o /dev/null -w '%{http_code}' --max-time 5 \
    --resolve "${host}:${port}:127.0.0.1" "http://${host}${path}" || true
}

wait_for_caddy_site() {
  local public_base="$1"
  local timeout="${2:-60}"
  local elapsed=0

  while ((elapsed < timeout)); do
    if caddy_probe "$public_base" "/health" >/dev/null 2>&1; then
      return 0
    fi
    sleep 3
    elapsed=$((elapsed + 3))
  done

  return 1
}
